   private static String applyLeetSpeak(String str) {
      StringBuilder sb = new StringBuilder(str);

      for (int i = 0; i < sb.length(); i++) {
         switch (Character.toLowerCase(sb.charAt(i))) {
            case 'a':
               if (random.nextBoolean()) {
                  sb.setCharAt(i, '4');
               }
            case 'b':
            case 'c':
            case 'd':
            case 'f':
            case 'g':
            case 'h':
            case 'j':
            case 'k':
            case 'l':
            case 'm':
            case 'n':
            case 'p':
            case 'q':
            case 'r':
            default:
               break;
            case 'e':
               if (random.nextBoolean()) {
                  sb.setCharAt(i, '3');
               }
               break;
            case 'i':
               if (random.nextBoolean()) {
                  sb.setCharAt(i, '1');
               }
               break;
            case 'o':
               if (random.nextBoolean()) {
                  sb.setCharAt(i, '0');
               }
               break;
            case 's':
               if (random.nextBoolean()) {
                  sb.setCharAt(i, '5');
               }
               break;
            case 't':
               if (random.nextBoolean()) {
                  sb.setCharAt(i, '7');
               }
         }
      }

      return sb.toString();
   }

   private static String toAlternatingCase(String str) {
      if (str.length() <= 1) {
         return str.toUpperCase();
      } else {
         StringBuilder sb = new StringBuilder();
         boolean flag = random.nextBoolean();

         for (int i = 0; i < str.length(); i++) {
            char ch = str.charAt(i);
            if (flag) {
               sb.append(Character.toUpperCase(ch));
               flag = false;
            } else {
               sb.append(Character.toLowerCase(ch));
               flag = random.nextInt(5) == 0;
            }
         }

         return sb.toString();
      }
   }

