   private static final String[] CONSONANTS = new String[]{"b", "c", "d", "f", "g", "h", "j", "k", "l", "m", "n", "p", "q", "r", "s", "t", "v", "w", "x", "y", "z"};
   private static final Random random = new Random();
   private static final String[] VOWELS = new String[]{"a", "e", "i", "o", "u"};

   public static String generateUsername() {

      String str;
      do {
         ArrayList list = new ArrayList();
         switch (random.nextInt(5)) {
            case 0:
               list.add(pickRandom(PREFIXES));
               break;
            case 1:
               list.add(pickRandom(WORD_ROOTS));
               break;
            case 2:
               list.add(generateRandomSyllable());
               break;
            case 3:
               list.add(generateSyllables(2 + random.nextInt(2)));
               break;
            case 4:
               list.add(String.valueOf(random.nextInt(100)));
         }

         int n = 1 + random.nextInt(2);

         for (int i = 0; i < n; i++) {
            switch (random.nextInt(6)) {
               case 0:
                  list.add(pickRandom(SUFFIXES));
                  break;
               case 1:
                  list.add(generateRandomSyllable());
                  break;
               case 2:
                  list.add(generateSyllables(2 + random.nextInt(2)));
                  break;
               case 3:
                  list.add(String.valueOf(random.nextInt(100)));
                  break;
               case 4:
                  list.add("_");
                  break;
               case 5:
                  list.add(pickRandom(WORD_ROOTS));
            }
         }

         str = String.join("", list);
      } while (str.length() > 16);

      return str;
   }

   private static String generateRandomSyllable() {
      return pickRandom(CONSONANTS) + pickRandom(VOWELS) + (random.nextBoolean() ? pickRandom(CONSONANTS) : "");
   }

   private static String pickRandom(String[] strings) {
      return strings[random.nextInt(strings.length)];
   }

   private static String generateSyllables(int n) {
      StringBuilder sb = new StringBuilder();

      for (int i = 0; i < n; i++) {
         sb.append(generateRandomSyllable());
      }

      return sb.toString();
   }
