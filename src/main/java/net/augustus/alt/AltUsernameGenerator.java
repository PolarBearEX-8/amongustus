   private static String applyDecorations(String str) {
      if (random.nextInt(10) < 3) {
         str = addRandomNumbers(str);
      }

      if (random.nextInt(20) < 1) {
         str = applyLeetSpeak(str);
      }

      if (random.nextInt(19) == 0) {
         str = addWrapperAffix(str);
      }

      return str;
   }

   private static String addWrapperAffix(String str) {
      String[] strings = new String[]{"_", "x", "X"};
      String str2 = strings[random.nextInt(strings.length)];
      switch (random.nextInt(3)) {
         case 0:
            return str2 + str + str2;
         case 1:
            return str2 + str;
         case 2:
            return str + str2;
         default:
            return str;
      }
   }

   private static String pickRandom(List list) {
      return (String)list.get(random.nextInt(list.size()));
   }

   private static String buildAffixedName() {
      ArrayList list = new ArrayList();
      list.add(pickRandom(PREFIXES) + pickRandom(NOUNS));
      list.add(pickRandom(NOUNS) + pickRandom(SUFFIXES));
      list.add(pickRandom(PREFIXES) + pickRandom(ADJECTIVES) + pickRandom(NOUNS));
      list.add(pickRandom(ADJECTIVES) + pickRandom(NOUNS) + pickRandom(SUFFIXES));
      return pickRandom(list);
   }

   public static String generateUsername() {

      try {
         ArrayList list = new ArrayList();
         list.add(buildTwoWordName());
         list.add(buildThreeWordName());
         list.add(buildAffixedName());
         list.add(buildMixedPartsName());
         String str = (String)list.get(random.nextInt(list.size()));
         str = randomizeCase(str);
         return applyDecorations(str);
      } catch (Throwable e) {
         e.printStackTrace();
         return "";
      }
   }

   private static String buildMixedPartsName() {
      int n = random.nextInt(3) + 2;
      StringBuilder sb = new StringBuilder();

      for (int i = 0; i < n; i++) {
         switch (random.nextInt(5)) {
            case 0:
               sb.append(pickRandom(PREFIXES));
               break;
            case 1:
               sb.append(pickRandom(SUFFIXES));
               break;
            case 2:
               sb.append(pickRandom(ADJECTIVES));
               break;
            case 3:
               sb.append(pickRandom(NOUNS));
               break;
            case 4:
               sb.append(pickRandom(VERBS));
         }
      }

      return sb.toString();
   }

